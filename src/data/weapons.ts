// Helper to calculate upgraded weapon stats
export function getUpgradedWeapon(weapon: Weapon, level: number): Weapon {
  const levelDiff = level - 1;
  const dmgBonus = 1 + levelDiff * 0.18; // +18% damage per level
  const capBonus = Math.floor(weapon.capacity * (1 + levelDiff * 0.15));
  const rateBonus = 1 + levelDiff * 0.08;
  const reloadReduction = Math.max(0.6, 1 - levelDiff * 0.08);

  return {
    ...weapon,
    level,
    baseDamage: Math.round(weapon.baseDamage * dmgBonus),
    capacity: capBonus,
    currentAmmo: capBonus,
    fireRate: Number((weapon.fireRate * rateBonus).toFixed(1)),
    reloadTime: Number((weapon.reloadTime * reloadReduction).toFixed(2)),
  };
}

export function getUpgradeCost(weapon: Weapon): number {
  return Math.round(400 * Math.pow(1.6, weapon.level - 1));
}
